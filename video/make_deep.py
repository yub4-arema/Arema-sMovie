def lines(d, x, y, items, size=28, col=INK, gap=14, anchor="la"):
    for i, t in enumerate(items):
        d.text((x, y + i * (size + gap)), t, font=F(size), fill=col, anchor=anchor)

def tag(d, x, y, s, col=ORANGE, size=22):
    w = F(size).getlength(s) + 28
    d.rounded_rectangle([x, y, x + w, y + size + 14], 12, fill=col)
    d.text((x + 14, y + 7), s, font=F(size), fill="white")
    return w

def src(d, kind):
    """出典ラベル。資料に書かれていること / 一般的な仕組み / 推測 を区別する。"""
    col, s = {"blog": (PURPLE, "ブログに書かれていること"), "paper": (GREEN, "Moshi論文に書かれていること"),
              "gen": (GRAY, "一般的な仕組みの説明"), "guess": (ORANGE, "推測(書かれていない)"),
              "news": (ORANGE, "報道・第三者の記事"), "claim": (ORANGE, "Blockの主張(未検証)")}[kind]
    tag(d, 1240 - F(22).getlength(s) - 28, 24, s, col)

def chapter(num, name, blurb, skip):
    def f(d):
        text(d, 640, 150, f"第{num}章", 54, GRAY, "ma", True)
        text(d, 640, 245, name, 64, INK, "ma", True)
        text(d, 640, 360, blurb, 32, GRAY, "ma")
        text(d, 640, 450, skip, 28, ORANGE, "ma")
    return f

def head(d, s, kind=None):
    title(d, s)
    if kind: src(d, kind)

def arrowdown(d, x, y1, y2, col=INK): arrow(d, x, y1, x, y2, col)

